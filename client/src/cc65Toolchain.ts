const C_IDENTIFIER_RE = /^[A-Za-z_][A-Za-z0-9_]*$/;

/** asm `_foo` -> C `foo`, or undefined if the name does not follow the cc65 convention. */
export function asmNameToCName(asmName: string): string | undefined {
    if (!asmName.startsWith('_')) return undefined;
    const cName = asmName.slice(1);
    return C_IDENTIFIER_RE.test(cName) ? cName : undefined;
}

/** True when a clang USR denotes a C symbol with external linkage named `cName`. */
export function isExternalCUsr(usr: string | undefined, cName: string): boolean {
    if (!usr) return false;
    // Functions: c:@F@name, variables: c:@name. Statics and locals embed the file name (c:file.c@...).
    return usr === `c:@F@${cName}` || usr === `c:@${cName}`;
}

/**
 * Parses the USR of a file-scope C function or variable. External symbols look like `c:@F@name` /
 * `c:@name`; statics embed their file (`c:main.c@F@name` / `c:main.c@name`). Locals, types, macros
 * and enum constants return undefined.
 */
export function parseFileScopeCUsr(usr: string | undefined): { name: string; isStatic: boolean } | undefined {
    if (!usr) return undefined;
    const m = /^c:([^@]*)@(?:F@)?([A-Za-z_][A-Za-z0-9_]*)$/.exec(usr);
    if (!m) return undefined;
    return { name: m[2], isStatic: m[1].length > 0 };
}

