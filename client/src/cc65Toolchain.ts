function exeName(base: string): string {
    return process.platform === 'win32' ? `${base}.exe` : base;
}

async function fileExists(p: string): Promise<boolean> {
    try {
        await fs.access(p);
        return true;
    } catch {
        return false;
    }
}

/**
 * Locates the cc65 C compiler: the explicit setting, then cc65 on PATH, then a cc65 next to the
 * configured ca65. Returns undefined when no cc65 is installed.
 */
export async function findCc65Compiler(options: { cc65Path?: string; ca65Path?: string }): Promise<string | undefined> {
    if (options.cc65Path) {
        return (await which(options.cc65Path, { nothrow: true })) ?? undefined;
    }
    const onPath = await which('cc65', { nothrow: true });
    if (onPath) return onPath;
    if (options.ca65Path) {
        const sibling = path.join(path.dirname(options.ca65Path), exeName('cc65'));
        if (await fileExists(sibling)) return sibling;
    }
    return undefined;
}

/**
 * Locates an executable from the cc65 toolchain (cc65, else ca65) used to infer the install layout.
 */
export async function findCc65Executable(options: { cc65Path?: string; ca65Path?: string } = {}): Promise<string | undefined> {
    const compiler = await findCc65Compiler(options);
    if (compiler) return compiler;
    if (options.ca65Path) return options.ca65Path;
    return (await which('ca65', { nothrow: true })) ?? undefined;
}

/**
 * Finds the cc65 system include directory (the one containing cc65's `stdio.h`).
 * Search order: explicit setting, CC65_INC, CC65_HOME/include, paths relative to the toolchain
 * executable, then common install prefixes.
 */
export async function resolveCc65IncludeDir(options: {
    explicit?: string;
    executable?: string;
    env?: NodeJS.ProcessEnv;
}): Promise<string | undefined> {
    const env = options.env ?? process.env;
    const candidates: string[] = [];
    if (options.explicit) candidates.push(options.explicit);
    if (env.CC65_INC) candidates.push(env.CC65_INC);
    if (env.CC65_HOME) candidates.push(path.join(env.CC65_HOME, 'include'));

    if (options.executable) {
        let exe = options.executable;
        try {
            exe = await fs.realpath(exe);
        } catch {
            // keep the unresolved path
        }
        const prefix = path.dirname(path.dirname(exe));
        candidates.push(
            path.join(prefix, 'share', 'cc65', 'include'),
            path.join(prefix, 'include'),
            path.join(prefix, 'lib', 'cc65', 'include'),
        );
    }

    candidates.push(
        '/usr/share/cc65/include',
        '/usr/local/share/cc65/include',
        '/opt/homebrew/share/cc65/include',
        '/usr/lib/cc65/include',
    );

    for (const candidate of candidates) {
        if (await isDirectoryWithStdio(candidate)) {
            return candidate;
        }
    }
    return undefined;
}

/** Converts `cc65 --version` output (e.g. "cc65 V2.19 - Git 1234") into the `__CC65__` value. */
export function parseCc65VersionMacro(versionOutput: string): string | undefined {
    const m = /V(\d+)\.(\d+)/.exec(versionOutput);
    if (!m) return undefined;
    const major = Number(m[1]);
    const minor = Number(m[2]);
    if (!Number.isFinite(major) || !Number.isFinite(minor)) return undefined;
    return `0x${((major << 8) | minor).toString(16).padStart(4, '0')}`;
}

export async function detectCc65VersionMacro(executable?: string): Promise<string> {
    if (!executable || !/cc65(\.exe)?$/i.test(path.basename(executable))) {
        return DEFAULT_CC65_VERSION_MACRO;
    }
    try {
        const { stdout, stderr } = await execFileAsync(executable, ['--version'], { timeout: 3000 });
        return parseCc65VersionMacro(`${stdout}\n${stderr}`) ?? DEFAULT_CC65_VERSION_MACRO;
    } catch (err: any) {
        // cc65 prints its version to stderr and may exit non-zero on some builds.
        const out = `${err?.stdout ?? ''}\n${err?.stderr ?? ''}`;
        return parseCc65VersionMacro(out) ?? DEFAULT_CC65_VERSION_MACRO;
    }
}

/**
 * Builds the clang flags that approximate cc65 compilation:
 * - `--target=msp430` gives 16-bit `int`, `size_t` and pointers like cc65.
 * - `-funsigned-char` matches cc65's unsigned `char`.
 * - `-nostdinc` + the cc65 include dir keeps host libc headers out.
 */
export function buildCc65ClangFlags(options: {
    target?: string;
    includeDir?: string;
    shimHeaderPath?: string;
    versionMacro?: string;
    userIncludeDirs?: string[];
    extraFlags?: string[];
}): string[] {
    const flags = [
        '--target=msp430',
        '-xc',
        '-std=gnu99',
        '-funsigned-char',
        '-fno-builtin',
        '-nostdinc',
        '-Wno-unknown-pragmas',
        '-Wno-main-return-type',
        `-D__CC65__=${options.versionMacro ?? DEFAULT_CC65_VERSION_MACRO}`,
    ];
    for (const define of getCc65TargetDefines(options.target)) {
        flags.push(`-D${define}=1`);
    }
    if (options.shimHeaderPath) {
        flags.push('-include', options.shimHeaderPath);
    }
    if (options.includeDir) {
        flags.push('-isystem', options.includeDir);
    }
    for (const dir of options.userIncludeDirs ?? []) {
        flags.push(`-I${dir}`);
    }
    flags.push(...(options.extraFlags ?? []));
    return flags;
}

/** Produces compile_commands.json entries for the given C sources. */
export function buildCompileCommands(
    files: Array<{ file: string; directory: string }>,
    flags: string[]
): CompileCommand[] {
    return files
        .slice()
        .sort((a, b) => a.file.localeCompare(b.file))
        .map(({ file, directory }) => ({
            directory,
            file,
            arguments: ['clang', ...flags, '-c', file],
        }));
}

/** Returns the sorted, de-duplicated set of directories that contain the given headers. */
export function collectHeaderDirs(headerPaths: string[], limit: number = 64): string[] {
    const dirs = Array.from(new Set(headerPaths.map(p => path.dirname(p)))).sort();
    return dirs.slice(0, limit);
}

/** Writes a file only if its contents changed. Returns true when the file was (re)written. */
export async function writeFileIfChanged(filePath: string, contents: string): Promise<boolean> {
    try {
        const existing = await fs.readFile(filePath, 'utf8');
        if (existing === contents) return false;
    } catch {
        // missing file
    }
    await fs.mkdir(path.dirname(filePath), { recursive: true });
    await fs.writeFile(filePath, contents, 'utf8');
    return true;
}

