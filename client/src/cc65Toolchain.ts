export type Cc65DiagnosticSeverity = 'error' | 'warning' | 'info';

export interface Cc65ToolDiagnostic {
    /** Absolute path of the file the message refers to (undefined for tool-level messages). */
    file?: string;
    /** 1-based line. */
    line?: number;
    severity: Cc65DiagnosticSeverity;
    message: string;
}

const ASM_ORIGIN_NOTE = 'Assembly code generated from this line';

/**
 * Parses cc65/ca65 messages (`file.c(12): Error: ...`, `cc65: Error: ...`). A ca65 error in cc65's
 * generated assembly is followed by `file.c(3): Note: Assembly code generated from this line` (with
 * `cc65 -g`); such errors are re-targeted onto that C line.
 */
export function parseCc65ToolOutput(output: string, cwd: string): Cc65ToolDiagnostic[] {
    const result: Cc65ToolDiagnostic[] = [];
    for (const rawLine of output.split(/\r?\n/)) {
        const line = rawLine.trimEnd();
        if (!line) continue;
        let file: string | undefined;
        let lineNo: number | undefined;
        let kind: string;
        let message: string;
        const located = /^(.*?)\((\d+)\):\s*(Error|Warning|Fatal|Note):\s*(.*)$/.exec(line);
        if (located) {
            file = path.resolve(cwd, located[1]);
            lineNo = Number(located[2]);
            kind = located[3];
            message = located[4];
        } else {
            const general = /^(?:cc65|ca65):\s*(Error|Warning|Fatal|Note):\s*(.*)$/.exec(line);
            if (!general) continue;
            kind = general[1];
            message = general[2];
        }

        if (kind === 'Note' && message === ASM_ORIGIN_NOTE) {
            const previous = result[result.length - 1];
            if (previous && file) {
                previous.file = file;
                previous.line = lineNo;
            }
            continue;
        }
        result.push({
            file,
            line: lineNo,
            severity: kind === 'Warning' ? 'warning' : kind === 'Note' ? 'info' : 'error',
            message,
        });
    }
    return result;
}

/** Parses the dependencies of the first rule of a make-style dependency file (`cc65 --create-dep`). */
export function parseMakeDependencies(text: string, cwd: string): string[] {
    const joined = text.replace(/\\\r?\n/g, ' ');
    const firstRule = joined.split(/\r?\n/).find(l => l.includes(':'));
    if (!firstRule) return [];
    const deps = firstRule.slice(firstRule.indexOf(':') + 1);
    const tokens = deps.match(/(?:\\ |[^\s])+/g) ?? [];
    return tokens.map(t => path.resolve(cwd, t.replace(/\\ /g, ' ')));
}

