/**
 * Helpers that describe the cc65 C dialect to clangd: locating the cc65 headers, generating a
 * shim header for cc65-only keywords, and producing a compile_commands.json for the workspace.
 *
 * This module intentionally has no dependency on the `vscode` API so it can be unit tested.
 */
import * as path from 'path';
import * as fs from 'fs/promises';
import { execFile } from 'child_process';
import { promisify } from 'util';
import which = require('which');

const execFileAsync = promisify(execFile);

/** Fallback `__CC65__` value (cc65 V2.19) when the version cannot be detected. */
export const DEFAULT_CC65_VERSION_MACRO = '0x0213';

/**
 * Shim header force-included into every C file. It maps cc65-only keywords and pseudo variables
 * onto constructs clang understands, so the cc65 headers and user sources parse cleanly.
 */
export const CC65_SHIM_HEADER = `/* Generated by the ca65 VS Code extension for clangd. Do not edit. */
#ifndef CA65_VSCODE_CC65_SHIM_H
#define CA65_VSCODE_CC65_SHIM_H
#define __fastcall__
#define __cdecl__
#define __near__
#define __far__
#define fastcall
#define cdecl
/* Inline asm: keep the arguments (e.g. the %v variable) visible to clangd as an unevaluated
   expression, so references, hover and rename see them. cc65 only allows asm inside functions. */
#define __asm__(...) ((void)sizeof((__VA_ARGS__, 1)))
#define asm(...) __asm__(__VA_ARGS__)
#define __CC65_STD_C89__ 1
#define __CC65_STD_C99__ 2
#define __CC65_STD_CC65__ 3
#define __CC65_STD__ __CC65_STD_CC65__
/* cc65 register pseudo variables */
extern unsigned char __A__;
extern unsigned char __X__;
extern unsigned char __Y__;
extern unsigned int __AX__;
extern unsigned long __EAX__;
#endif
`;

