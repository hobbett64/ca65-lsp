/** Builds the cc65 command line used to compile one C file to assembly. */
export function buildCc65CompileArgs(options: {
    target?: string;
    /** Explicit CPU (`ca65.cpu` other than auto); W65C02 is passed as 65C02, which the compiler knows. */
    cpu?: string;
    includeDirs?: string[];
    extraFlags?: string[];
    /** Raw cc65 options from `ca65.cc65.additionalArgs` (already sanitized). */
    additionalArgs?: string[];
    outFile: string;
    file: string;
}): string[] {
    const args: string[] = [];
    if (options.target) args.push('-t', options.target);
    if (options.cpu) args.push('--cpu', options.cpu.toUpperCase() === 'W65C02' ? '65C02' : options.cpu);
    for (const dir of options.includeDirs ?? []) args.push('-I', dir);
    // Only pass through flags cc65 understands with the same syntax as clang.
    for (const flag of options.extraFlags ?? []) {
        if (/^-[DI]./.test(flag)) args.push(flag);
    }
    args.push(...(options.additionalArgs ?? []));
    args.push('-o', options.outFile, options.file);
    return args;
}

