/** cc65 options the extension controls itself (output/dependency files); dropped from user arguments. */
const CC65_RESERVED_OPTIONS_WITH_VALUE = new Set(['-o', '--create-dep', '--create-full-dep', '--dep-target']);

/** Removes output/dependency options from `ca65.cc65.additionalArgs`. */
export function sanitizeCc65AdditionalArgs(args: readonly unknown[]): string[] {
    const result: string[] = [];
    for (let i = 0; i < args.length; i++) {
        const arg = args[i];
        if (typeof arg !== 'string' || arg.length === 0) continue;
        if (CC65_RESERVED_OPTIONS_WITH_VALUE.has(arg)) {
            i++; // skip its value
            continue;
        }
        if (/^-o./.test(arg) || /^--(?:create-dep|create-full-dep|dep-target)=/.test(arg)) continue;
        result.push(arg);
    }
    return result;
}

export interface Cc65AssemblyView {
    /** Generated assembly with `.dbg` bookkeeping lines removed. */
    text: string;
    /** 0-based C line -> inclusive ranges of 0-based lines in `text`. */
    cToAsm: Map<number, Array<[number, number]>>;
    /** 0-based line in `text` -> 0-based C line (undefined for lines not attributed to the source). */
    asmToC: Array<number | undefined>;
    /** 0-based line in `text` -> 0-based line in cc65's original output (for listing lookups). */
    sourceLineIndex: number[];
    /**
     * Included file basename -> ranges of lines generated from it (a function that comes entirely from
     * the header covers its whole block, banner to `.endproc`).
     */
    headerRanges: Map<string, Array<[number, number]>>;
}

/**
 * Prepares `cc65 -g --add-source` output for display: strips `.dbg` directives and records which
 * assembly lines (including the `--add-source` comment block) belong to which line of the C source.
 */
export function buildCc65AssemblyView(asmText: string, sourceBaseName: string): Cc65AssemblyView {
    const out: string[] = [];
    const asmToC: Array<number | undefined> = [];
    const sourceLineIndex: number[] = [];
    const cToAsm = new Map<number, Array<[number, number]>>();
    const headerRanges = new Map<string, Array<[number, number]>>();
    const MAIN = '';
    // A region of output generated from one line: of the C source (cLine) or of an included file.
    let current: { cLine?: number; file?: string; start: number } | undefined;
    // The function being emitted, and which files its code came from.
    let proc: { start: number; files: Set<string> } | undefined;

    const addRange = (map: Map<any, Array<[number, number]>>, key: any, start: number, end: number) => {
        const ranges = map.get(key) ?? [];
        ranges.push([start, end]);
        map.set(key, ranges);
    };
    const closeCurrent = (end: number) => {
        if (current && end >= current.start) {
            if (current.cLine !== undefined) addRange(cToAsm, current.cLine, current.start, end);
            else if (current.file !== undefined) addRange(headerRanges, current.file, current.start, end);
        }
        current = undefined;
    };

    /**
     * Start of the `--add-source` comment block (`;` / `; source line(s)` / `;`) at the end of the
     * output, or out.length if there is none. cc65 emits it right before the line's `.dbg line`.
     */
    const trailingSourceBlockStart = (): number => {
        const n = out.length;
        if (n === 0 || out[n - 1].trim() !== ';') return n;
        for (let i = n - 2; i >= 0; i--) {
            const t = out[i].trim();
            if (t === ';') return i;
            if (!t.startsWith(';') || /^;\s*-{4,}/.test(t)) return n;
        }
        return n;
    };

    const asmLines = asmText.split(/\r?\n/);
    for (let originalIndex = 0; originalIndex < asmLines.length; originalIndex++) {
        const line = asmLines[originalIndex];
        const dbgLine = /^\s*\.dbg\s+line\b(?:\s*,\s*"([^"]*)"\s*,\s*(\d+))?/.exec(line);
        if (dbgLine) {
            // The comment block just above belongs to the line starting here, not the previous one.
            const blockStart = trailingSourceBlockStart();
            closeCurrent(blockStart - 1);
            const file = dbgLine[1] !== undefined ? path.basename(dbgLine[1]) : undefined;
            const ours = file === sourceBaseName;
            const cLine = ours ? Number(dbgLine[2]) - 1 : undefined;
            for (let i = blockStart; i < out.length; i++) asmToC[i] = cLine;
            if (cLine !== undefined) current = { cLine, start: blockStart };
            else if (file !== undefined) current = { file, start: blockStart };
            if (file !== undefined) proc?.files.add(ours ? MAIN : file);
            continue;
        }
        if (/^\s*\.dbg\b/.test(line)) continue;
        if (/^\.proc\b/i.test(line)) {
            // The function's block starts at its banner (`; ----` / `; signature` / `; ----`) and `.segment`.
            let start = out.length;
            while (start > 0 && (out[start - 1].startsWith(';') || /^\.segment\b/.test(out[start - 1]) || out[start - 1].trim() === '')) start--;
            while (start < out.length && out[start].trim() === '') start++;
            proc = { start, files: new Set() };
        }
        const isEndProc = /^\s*\.endproc\b/i.test(line);
        if (isEndProc) closeCurrent(out.length - 1);
        out.push(line);
        asmToC.push(current?.cLine);
        sourceLineIndex.push(originalIndex);
        if (isEndProc && proc) {
            const files = [...proc.files];
            if (files.length === 1 && files[0] !== MAIN) addRange(headerRanges, files[0], proc.start, out.length - 1);
            proc = undefined;
        }
    }
    closeCurrent(out.length - 1);
    while (out.length > 0 && out[out.length - 1].trim() === '') {
        out.pop();
        asmToC.pop();
        sourceLineIndex.pop();
    }
    return { text: out.join('\n') + '\n', cToAsm, asmToC, sourceLineIndex, headerRanges };
}

// -------------------------------------------------------------------------------------------------
// cc65 calling convention (for asm functions called from C and C functions called from asm)
// -------------------------------------------------------------------------------------------------

export interface CParameter {
    name?: string;
    /** Type as written (e.g. `uint8_t`). */
    type: string;
    /** Canonical type (e.g. `unsigned char`). */
    canonical: string;
}

export type Cc65CallingConvention = 'fastcall' | 'cdecl';

export interface CFunctionPrototype {
    name: string;
    returnType: string;
    returnCanonical: string;
    params: CParameter[];
    variadic: boolean;
    convention: Cc65CallingConvention;
}

/** `uint8_t index (aka unsigned char)` -> type/canonical/name. */
function parseTypedName(text: string): { type: string; canonical: string; name?: string } {
    let main = text.trim();
    let canonical: string | undefined;
    const aka = /\s*\(aka (.+)\)$/.exec(main);
    if (aka) {
        canonical = aka[1].trim();
        main = main.slice(0, aka.index).trim();
    }
    const nameMatch = /^(.*?[\s*&])([A-Za-z_][A-Za-z0-9_]*)$/.exec(main);
    const TYPE_WORDS = /^(?:const|volatile|signed|unsigned|char|short|int|long|float|double|void|_Bool|bool|struct|union|enum)$/;
    if (nameMatch && !TYPE_WORDS.test(nameMatch[2]) && nameMatch[1].trim() !== '') {
        const type = nameMatch[1].trim();
        return { type, canonical: canonical ?? type, name: nameMatch[2] };
    }
    return { type: main, canonical: canonical ?? main };
}

/**
 * Parses clangd's markdown hover for a function (`### function `name``, `→ `ret``, `Parameters:` list,
 * and the declaration code block for `...`). Returns undefined for non-functions.
 */
export function parseClangdFunctionHover(markdown: string): Omit<CFunctionPrototype, 'convention'> | undefined {
    const header = /^###\s+function\s+`([^`]+)`/m.exec(markdown);
    if (!header) return undefined;
    const ret = /^→\s+`([^`]+)`/m.exec(markdown);
    const returned = ret ? parseTypedName(ret[1]) : { type: 'void', canonical: 'void' };
    const params: CParameter[] = [];
    const paramsBlock = /^Parameters:\s*\n((?:\s*-\s+`[^`]*`\s*\n?)+)/m.exec(markdown);
    if (paramsBlock) {
        for (const m of paramsBlock[1].matchAll(/-\s+`([^`]*)`/g)) {
            params.push(parseTypedName(m[1]));
        }
    }
    const code = /```[a-z]*\n([\s\S]*?)```/.exec(markdown)?.[1] ?? '';
    return {
        name: header[1],
        returnType: returned.type,
        returnCanonical: returned.canonical,
        params,
        variadic: /\.\.\.\s*\)/.test(code),
    };
}

/** Calling convention from the declaration's source text (`__fastcall__`/`__cdecl__`), else the default. */
export function detectCallingConvention(declarationText: string, defaultConvention: Cc65CallingConvention = 'fastcall'): Cc65CallingConvention {
    if (/\b(?:__cdecl__|cdecl)\b/.test(declarationText)) return 'cdecl';
    if (/\b(?:__fastcall__|fastcall)\b/.test(declarationText)) return 'fastcall';
    return defaultConvention;
}

/** Size in bytes of a canonical C type under cc65 (undefined when unknown, e.g. structs by value). */
export function cc65TypeSize(canonical: string): number | undefined {
    const t = canonical.replace(/\b(?:const|volatile|register|restrict)\b/g, ' ').replace(/\s+/g, ' ').trim();
    if (/[*[]/.test(t)) return 2; // pointers, arrays (decay), function pointers
    if (/^(?:(?:un)?signed )?char$|^_Bool$|^bool$/.test(t)) return 1;
    if (/^(?:(?:un)?signed )?(?:short(?: int)?|int)$|^(?:un)?signed$|^enum\b/.test(t)) return 2;
    if (/^(?:(?:un)?signed )?long(?: int)?$/.test(t)) return 4;
    if (/^(?:float|double)$/.test(t)) return 4;
    return undefined;
}

const REGISTER_PARTS: Record<number, string> = {
    1: 'A',
    2: 'A (lo), X (hi)',
    4: 'A (byte 0), X (byte 1), sreg (byte 2), sreg+1 (byte 3)',
};

export interface ArgumentLocation {
    name: string;
    type: string;
    size?: number;
    location: string;
}

export interface CallingConventionLayout {
    args: ArgumentLocation[];
    /** Bytes of arguments on the C stack (the callee pops them), undefined if a size is unknown. */
    stackBytes?: number;
    returns?: string;
    notes: string[];
}

/**
 * Where each argument is when a cc65-compiled caller jumps to the function: arguments are pushed
 * left to right on the C stack (`sp`, low byte first), so the last pushed is at `(sp),y=0`. With
 * `__fastcall__` (cc65's default) the last argument is passed in registers instead. Variadic
 * functions get every argument on the stack plus the argument byte count in Y. The callee pops its
 * stack arguments.
 */
export function describeCc65CallingConvention(proto: CFunctionPrototype): CallingConventionLayout {
    const notes: string[] = [];
    const params = proto.params.filter(p => p.canonical !== 'void');
    const inRegister = proto.convention === 'fastcall' && !proto.variadic && params.length > 0
        ? params[params.length - 1]
        : undefined;
    const onStack = inRegister ? params.slice(0, -1) : params;

    const args: ArgumentLocation[] = [];
    let offset = 0;
    let stackKnown = true;
    const stackLocations = new Map<CParameter, string>();
    for (let i = onStack.length - 1; i >= 0; i--) {
        const p = onStack[i];
        const size = cc65TypeSize(p.canonical);
        if (size === undefined || !stackKnown) {
            stackKnown = false;
            stackLocations.set(p, 'C stack (offset depends on a struct size)');
            continue;
        }
        stackLocations.set(p, size === 1
            ? `(sp),y=${offset}`
            : `(sp),y=${offset}..${offset + size - 1} (low byte first)`);
        offset += size;
    }
    params.forEach((p, i) => {
        const size = cc65TypeSize(p.canonical);
        const name = p.name ?? `arg${i + 1}`;
        const location = p === inRegister
            ? (size !== undefined ? REGISTER_PARTS[size] ?? 'registers' : 'registers')
            : stackLocations.get(p) ?? 'C stack';
        args.push({ name, type: p.type, size, location });
    });

    if (proto.variadic) {
        notes.push('Variadic: the variable arguments are pushed after the named ones (char promoted to int), so the offsets above are relative to the end of the variable arguments; Y holds the total argument byte count.');
    }
    if (inRegister && cc65TypeSize(inRegister.canonical) === undefined) {
        notes.push(`\`${inRegister.name ?? 'last argument'}\` is passed by value with an unknown size.`);
    }

    let returns: string | undefined;
    const retSize = cc65TypeSize(proto.returnCanonical);
    if (proto.returnCanonical !== 'void') {
        if (retSize === 1) {
            returns = /^signed char$/.test(proto.returnCanonical.trim())
                ? 'A, with X = sign extension ($FF if negative, else 0)'
                : 'A, with X = 0';
        } else if (retSize !== undefined) {
            returns = REGISTER_PARTS[retSize];
        } else {
            returns = 'registers (size unknown)';
        }
    }

    return { args, stackBytes: stackKnown ? offset : undefined, returns, notes };
}

function formatPrototype(proto: CFunctionPrototype): string {
    const params = proto.params.map(p => (p.name ? `${p.type}${p.type.endsWith('*') ? '' : ' '}${p.name}` : p.type));
    if (proto.variadic) params.push('...');
    const keyword = proto.convention === 'cdecl' ? '__cdecl__' : '__fastcall__';
    return `${proto.returnType} ${keyword} ${proto.name}(${params.length > 0 ? params.join(', ') : 'void'})`;
}

/** The C prototype as a code block, shown at the bottom of asm hovers for C functions. */
export function formatPrototypeMarkdown(proto: CFunctionPrototype): string {
    return ['```c', formatPrototype(proto), '```'].join('\n');
}

/** An asm implementation stub for a C prototype, with the argument locations as comments. */
export function buildAsmStub(proto: CFunctionPrototype): string {
    const layout = describeCc65CallingConvention(proto);
    const asmName = `_${proto.name}`;
    const lines: string[] = ['', `; ${formatPrototype(proto)}`];
    for (const a of layout.args) lines.push(`;   ${a.name}: ${a.location}`);
    lines.push(`;   returns: ${layout.returns ?? 'nothing'}`);
    const pop = layout.stackBytes ?? 0;
    const popInRange = pop > 0 && pop <= 8;
    if (popInRange) lines.push(`.import incsp${pop}`);
    lines.push(`.export ${asmName}`, `.proc ${asmName}`, '    ; TODO: implement');
    if (popInRange) {
        lines.push(`    jmp incsp${pop}          ; pop ${pop} argument byte${pop === 1 ? '' : 's'} and return`);
    } else if (pop > 8 || layout.stackBytes === undefined) {
        lines.push(`    ; pop the ${layout.stackBytes ?? '?'} argument bytes (ldy #N / jmp addysp) before returning`, '    rts');
    } else {
        lines.push('    rts');
    }
    lines.push('.endproc', '');
    return lines.join('\n');
}

/**
 * 0-based lines of file-scope variable definitions in C source (name -> line). `extern`
 * declarations, typedefs and functions are skipped; comments, strings and preprocessor lines are
 * ignored.
 */
export function findFileScopeVariableDefinitions(cSource: string): Map<string, number> {
    const result = new Map<string, number>();
    const n = cSource.length;
    let depth = 0;
    let line = 0;
    let statementWords: string[] = [];
    let atLineStart = true;
    let i = 0;
    const isIdentStart = (c: string) => /[A-Za-z_]/.test(c);
    const isIdent = (c: string) => /[A-Za-z0-9_]/.test(c);
    while (i < n) {
        const c = cSource[i];
        if (c === '\n') {
            line++;
            atLineStart = true;
            i++;
            continue;
        }
        if (atLineStart && c === '#') {
            // preprocessor line (with backslash continuations)
            while (i < n && cSource[i] !== '\n') {
                if (cSource[i] === '\\' && cSource[i + 1] === '\n') {
                    line++;
                    i++;
                }
                i++;
            }
            continue;
        }
        if (c !== ' ' && c !== '\t' && c !== '\r') atLineStart = false;
        if (c === '/' && cSource[i + 1] === '/') {
            while (i < n && cSource[i] !== '\n') i++;
            continue;
        }
        if (c === '/' && cSource[i + 1] === '*') {
            const end = cSource.indexOf('*/', i + 2);
            const stop = end < 0 ? n : end + 2;
            for (let k = i; k < stop; k++) if (cSource[k] === '\n') line++;
            i = stop;
            continue;
        }
        if (c === '"' || c === '\'') {
            i++;
            while (i < n && cSource[i] !== c && cSource[i] !== '\n') i += cSource[i] === '\\' ? 2 : 1;
            i++;
            continue;
        }
        if (c === '{') { depth++; i++; continue; }
        if (c === '}') {
            depth = Math.max(0, depth - 1);
            // A closed `struct {...}`/`union {...}` body is the type of what follows (`} point;`).
            if (depth === 0) statementWords = [...statementWords.filter(w => w === 'extern' || w === 'typedef'), '}'];
            i++;
            continue;
        }
        if (depth === 0 && c === ';') { statementWords = []; i++; continue; }
        if (isIdentStart(c)) {
            let j = i + 1;
            while (j < n && isIdent(cSource[j])) j++;
            const word = cSource.slice(i, j);
            if (depth === 0) {
                statementWords.push(word);
                let k = j;
                while (k < n && (cSource[k] === ' ' || cSource[k] === '\t')) k++;
                const next = cSource[k];
                const declaresVariable = (next === '=' && cSource[k + 1] !== '=') || next === ';' || next === ',' || next === '[';
                if (declaresVariable && !statementWords.includes('extern') && !statementWords.includes('typedef')
                    && statementWords.length > 1 && !result.has(word)) {
                    result.set(word, line);
                }
            }
            i = j;
            continue;
        }
        i++;
    }
    return result;
}

/**
 * Links cc65's data labels (`_name:` and the data lines after it) to the C line that defines the
 * variable. cc65 emits `.dbg line` only inside functions, so file-scope variables need this.
 */
export function linkDataDefinitions(view: Cc65AssemblyView, cSource: string): void {
    const definitions = findFileScopeVariableDefinitions(cSource);
    if (definitions.size === 0) return;
    const lines = view.text.split('\n');
    for (let i = 0; i < lines.length; i++) {
        const label = /^_([A-Za-z_][A-Za-z0-9_]*):/.exec(lines[i]);
        if (!label || view.asmToC[i] !== undefined) continue;
        const cLine = definitions.get(label[1]);
        if (cLine === undefined) continue;
        let end = i;
        while (end + 1 < lines.length && /^\s+\S/.test(lines[end + 1])) end++; // indented data lines
        const ranges = view.cToAsm.get(cLine) ?? [];
        ranges.push([i, end]);
        view.cToAsm.set(cLine, ranges);
        for (let k = i; k <= end; k++) view.asmToC[k] = cLine;
    }
}

/**
 * Replaces the declaration code block at the end of clangd's hover (which cannot show
 * `__fastcall__`/`__cdecl__`, hidden from clangd by the cc65 shim) with the cc65 prototype.
 * Returns the markdown unchanged when it has no code block.
 */
export function replaceClangdDeclarationBlock(markdown: string, prototypeMarkdown: string): string {
    const blocks = [...markdown.matchAll(/```[A-Za-z0-9_+-]*\n[\s\S]*?```/g)];
    const last = blocks[blocks.length - 1];
    if (!last || last.index === undefined) return markdown;
    return markdown.slice(0, last.index) + prototypeMarkdown + markdown.slice(last.index + last[0].length);
}

/** The declaration code block at the end of a clangd hover (as a ```c block), if any. */
export function extractClangdDeclarationBlock(markdown: string): string | undefined {
    const blocks = [...markdown.matchAll(/```[A-Za-z0-9_+-]*\n([\s\S]*?)```/g)];
    const last = blocks[blocks.length - 1];
    if (!last) return undefined;
    const code = last[1].split('\n').filter(l => !/^\s*\/\/ In /.test(l)).join('\n').trimEnd();
    return code ? ['```c', code, '```'].join('\n') : undefined;
}

/** Text without C comments (for checking which header mentions a name). */
function stripCComments(text: string): string {
    return text.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/\/\/[^\n]*/g, ' ');
}

/**
 * Links each `#include` line of the C source to what its header produced in the view:
 * - code the header defines (cc65 tags it with the header's name in its debug info), and
 * - the `.import`/`.importzp` lines of symbols the header declares (attributed to the first included
 *   header, in `#include` order, that mentions the C name).
 * Clicking such a line highlights the `#include` line.
 */
export function linkIncludes(
    view: Cc65AssemblyView,
    cSource: string,
    headers: Array<{ path: string; text: string }> = []
): void {
    const lines = cSource.split(/\r?\n/);
    const includes: Array<{ line: number; base: string }> = [];
    for (let i = 0; i < lines.length; i++) {
        const include = /^\s*#\s*include\s*[<"]([^>"]+)[>"]/.exec(lines[i]);
        if (include) includes.push({ line: i, base: path.basename(include[1]) });
    }
    if (includes.length === 0) return;

    const rangesByLine = new Map<number, Array<[number, number]>>();
    const add = (line: number, range: [number, number]) => {
        const list = rangesByLine.get(line) ?? [];
        list.push(range);
        rangesByLine.set(line, list);
    };

    // Code defined in a header.
    for (const inc of includes) {
        for (const range of view.headerRanges.get(inc.base) ?? []) add(inc.line, range);
    }

    // Imports of symbols declared in a header.
    const headerTexts = includes.map(inc => {
        const header = headers.find(h => path.basename(h.path) === inc.base);
        return header ? stripCComments(header.text) : undefined;
    });
    const viewLines = view.text.split('\n');
    for (let k = 0; k < viewLines.length; k++) {
        const imp = /^\s*\.import(?:zp)?\s+(.+)$/.exec(viewLines[k].replace(/;.*$/, ''));
        if (!imp || view.asmToC[k] !== undefined) continue;
        const names = imp[1].split(',').map(n => n.trim()).filter(n => /^_[A-Za-z_][A-Za-z0-9_]*$/.test(n));
        for (const name of names) {
            const re = new RegExp(`\\b${name.slice(1)}\\b`);
            const index = headerTexts.findIndex(text => text !== undefined && re.test(text));
            if (index >= 0) {
                add(includes[index].line, [k, k]);
                break;
            }
        }
    }

    for (const [line, ranges] of rangesByLine) {
        view.cToAsm.set(line, [...(view.cToAsm.get(line) ?? []), ...ranges]);
        for (const [start, end] of ranges) {
            for (let k = start; k <= end; k++) {
                if (view.asmToC[k] === undefined) view.asmToC[k] = line;
            }
        }
    }
}
